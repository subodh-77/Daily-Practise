class Solution {
public:
    long long countCommas(long long n) {

        if (n < 1000)
            return 0;

        else if (n <= 999999)
            return (n - 999) * 1;

        else if (n <= 999999999)
            return (999999 - 999) * 1
                 + (n - 999999) * 2;

        else if (n <= 999999999999LL)
            return (999999 - 999) * 1
                 + (999999999 - 999999) * 2
                 + (n - 999999999) * 3;

        else if (n <= 999999999999999LL)
            return (999999 - 999) * 1
                 + (999999999 - 999999) * 2
                 + (999999999999 - 999999999) * 3
                 + (n - 999999999999LL) * 4;

        else
            return (999999 - 999) * 1
                 + (999999999 - 999999) * 2
                 + (999999999999 - 999999999) * 3
                 + (999999999999999 - 999999999999) * 4
                 + (n - 999999999999999LL) * 5;
    }
};